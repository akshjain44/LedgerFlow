import Link from "next/link";
import { requireTenant } from "@/server/context";
import { withTenant } from "@/server/db";
import { Badge, Card, EmptyState, PageHeader } from "@/components/ui";
import { DateTimeText, PRIORITY_TONE } from "@/components/format";
import { ActionForm, SubmitButton } from "@/components/forms";
import { FilterChips, Pagination } from "@/components/ListControls";
import { markAllReadAction, markReadAction } from "@/actions/misc";
import { REMINDER_LABELS, type ReminderType } from "@/domain/reminderSchedule";
import { cn } from "@/lib/cn";

export const metadata = { title: "Notifications" };

const CATEGORY_GROUPS: Record<string, string[]> = {
  receivables: ["receivable_upcoming", "receivable_due_today", "receivable_overdue"],
  promises: ["promise_due_today", "promise_broken", "promise_repeated_broken"],
  payables: ["payable_upcoming", "payable_overdue", "planned_payment_due"],
  followups: ["followup_due"],
  disputes: ["dispute_review"],
  system: ["delivery_failure"],
};

export default async function NotificationsPage({ searchParams }: { searchParams: Promise<Record<string, string | undefined>> }) {
  const ctx = await requireTenant();
  const sp = await searchParams;
  const page = Math.max(Number(sp.page) || 1, 1);
  const where = {
    userId: ctx.userId,
    ...(sp.read === "unread" ? { readAt: null } : {}),
    ...(sp.category && CATEGORY_GROUPS[sp.category] ? { category: { in: CATEGORY_GROUPS[sp.category] } } : {}),
    ...(sp.priority ? { priority: sp.priority as never } : {}),
  };
  const [rows, total, unread] = await withTenant(ctx.businessId, (tx) =>
    Promise.all([
      tx.notification.findMany({ where, orderBy: { createdAt: "desc" }, skip: (page - 1) * 30, take: 30 }),
      tx.notification.count({ where }),
      tx.notification.count({ where: { userId: ctx.userId, readAt: null } }),
    ]),
  );
  const params = { read: sp.read, category: sp.category, priority: sp.priority };
  return (
    <>
      <PageHeader
        title="Notifications"
        description={`${unread} unread. Generated by the scheduled reminder processor and escalation rules.`}
        actions={unread > 0 ? <ActionForm action={markAllReadAction}><SubmitButton variant="secondary">Mark all as read</SubmitButton></ActionForm> : undefined}
      />
      <div className="mb-4 flex flex-wrap gap-3">
        <FilterChips path="/notifications" params={params} param="read" current={sp.read ?? ""} options={[{ key: "", label: "All" }, { key: "unread", label: "Unread" }]} />
        <FilterChips path="/notifications" params={params} param="category" current={sp.category ?? ""} options={[{ key: "", label: "Any type" }, { key: "receivables", label: "Receivables" }, { key: "promises", label: "Promises" }, { key: "payables", label: "Payables" }, { key: "followups", label: "Follow-ups" }, { key: "disputes", label: "Disputes" }, { key: "system", label: "Delivery issues" }]} />
        <FilterChips path="/notifications" params={params} param="priority" current={sp.priority ?? ""} options={[{ key: "", label: "Any priority" }, { key: "urgent", label: "Urgent" }, { key: "high", label: "High" }]} />
      </div>
      <Card padded={false}>
        {rows.length === 0 ? (
          <div className="p-4"><EmptyState title="No notifications">Reminders appear here when invoices approach or pass their due dates, promises fall due, or follow-ups are scheduled.</EmptyState></div>
        ) : (
          <ul className="divide-y divide-line">
            {rows.map((n) => (
              <li key={n.id} className={cn("flex flex-wrap items-start justify-between gap-3 px-4 py-3", !n.readAt && "bg-accent-soft/40")}>
                <div className="min-w-0 flex-1">
                  <div className="flex flex-wrap items-center gap-2">
                    {!n.readAt && <span className="h-2 w-2 rounded-full bg-accent" aria-label="Unread" />}
                    <Badge tone={PRIORITY_TONE[n.priority]}>{REMINDER_LABELS[n.category as ReminderType] ?? n.category.replace(/_/g, " ")}</Badge>
                    {n.link ? <Link href={n.link} className="font-medium hover:underline">{n.title}</Link> : <span className="font-medium">{n.title}</span>}
                  </div>
                  {n.body && <p className="mt-1 text-[13.5px] text-ink-2">{n.body}</p>}
                  <p className="mt-1 text-[12px] text-muted"><DateTimeText value={n.createdAt} tz={ctx.timezone} /></p>
                </div>
                {!n.readAt && (
                  <ActionForm action={markReadAction}>
                    <input type="hidden" name="id" value={n.id} />
                    <SubmitButton variant="secondary" size="sm">Mark read</SubmitButton>
                  </ActionForm>
                )}
              </li>
            ))}
          </ul>
        )}
        <Pagination path="/notifications" params={params} page={page} pageSize={30} total={total} />
      </Card>
    </>
  );
}
